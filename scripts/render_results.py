#!/usr/bin/env python3
"""Render manuscript tables and TikZ plots from data/results/aggregates.csv."""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = [('gemma-4-26B-A4B-it', 'Gemma'), ('qwen3.6-35B-A3B', 'Qwen')]


def render(root):
    with (root / 'data/results/aggregates.csv').open() as handle:
        rows = list(csv.DictReader(handle))
    index = {(r['model'], r['group'], r['factor'], r['level'], r['metric']): r for r in rows}
    files = {}

    def record(model, group, factor, level, metric):
        return index[model, group, factor, str(level), metric]

    def value(model, group, factor, level, metric):
        raw = record(model, group, factor, level, metric)['value']
        return float(raw) if raw else None

    def percent(model, group, factor, level, metric):
        v = value(model, group, factor, level, metric)
        return f'{100*v:.2f}' if v is not None else '--'

    def table(path, caption, label, columns, headings, body, wide=False, note=''):
        env = 'table*' if wide else 'table'
        files[path] = '\n'.join([
            '% Generated by python3 scripts/render_results.py; source: data/results/aggregates.csv.',
            rf'\begin{{{env}}}[t]', r'\centering', rf'\caption{{{caption}}}',
            rf'\label{{{label}}}', r'\scriptsize', r'\setlength{\tabcolsep}{3pt}',
            rf'\begin{{tabular}}{{{columns}}}', r'\toprule', headings + r' \\',
            r'\midrule', *[r'\midrule' if row is None else ' & '.join(row) + r' \\' for row in body],
            r'\bottomrule', r'\end{tabular}', note, rf'\end{{{env}}}', '',
        ])

    body = []
    for group, name in [('all', 'All'), ('unguarded', 'Unguarded'), ('condition', 'Condition-aware')]:
        for model, short in MODELS:
            n = record(model, group, 'overall', 'all', 'answer')['denominator']
            body.append([name, short, f'{int(n):,}', *[percent(model, group, 'overall', 'all', k) for k in ['answer','path','nr']]])
        body.append(None)
    table('tables/overall_performance.tex',
          r'Answer and trace correctness (\%) for unguarded (U: \mbox{\texttt{n\_if}$=0$}) and condition-aware (C: \mbox{\texttt{n\_if}}$\in\{1,3,5\}$) questions. Non-responses (NR) remain in both denominators.',
          'tab:overall', 'llrrrr', r'Group & Model & $N$ & Answer & Trace & NR', body[:-1])

    body = []
    for factor, label, low, high in [('if', r'\path{n_if}: 1 to 5', 1, 5), ('param',r'\path{n_params}: 0 to 2',0,2),
                                    ('context',r'\path{class_size}: 100 to 500',100,500), ('comment',r'\path{n_comment}: 0 to 1',0,1),
                                    ('var',r'\path{n_vars}: 0 to 2',0,2), ('loop',r'\path{n_loops}: 0 to 2',0,2)]:
        fields = [label]
        for model, short in MODELS:
            for metric in ['answer','path']:
                group = 'all' if factor == 'if' else 'condition'
                delta = 100*(value(model,group,factor,high,metric)-value(model,group,factor,low,metric))
                fields.append(f'{delta:+.2f}')
        body.append(fields)
    table('tables/factor_effects.tex', r'Score differences within condition-aware questions (percentage points, high minus low). A and T denote answer and trace correctness, with other factors averaged over the balanced grid.',
          'tab:factors','lrrrr',r'Contrast & Gemma A & Gemma T & Qwen A & Qwen T',body)

    body=[]
    for model, short in MODELS:
        for truth, label in [('True','Positive'),('False','Negative')]:
            body.append([short,label,*[percent(model,'condition','expected_truth',truth,k) for k in ['answer','path','t04','t05']]])
    table('tables/trace_diagnostics.tex', r'Condition-aware scores by polarity (\%). Each polarity has 17,496 questions per model. T04 gives the mean omitted fraction, while T05 gives the incidence of traces containing an existing method outside the executable region. Both are negative-only diagnostics.',
          'tab:trace-diagnostics','llrrrr',r'Model & Polarity & Answer & Trace & T04 & T05',body)

    body=[]
    for model, short in MODELS:
        for param in [1,2]:
            fields=[short,str(param)]
            for key in ['if_difficulty_attributable','misjudged_if_difficulty_mean','correct_if_difficulty_mean','theoretical_if_difficulty_mean']:
                fields.append(f'{value(model,"condition","param",param,key):.2f}')
            body.append(fields)
    table('tables/value_origin_difficulty.tex',
          r'Value-origin distance in method boundaries. D1$^*$ restricts D1 to the same unambiguous attribution population as D3/D5. D3 concerns attributed errors, while D5 concerns exposed guards without an attributed error. D9 is question-weighted reference difficulty. Counts appear in Table~\ref{tab:difficulty-populations}.',
          'tab:value-origin','lrrrrr',r'Model & \path{n_params} & D1$^*$ & D3 & D5 & D9',body)

    body=[]
    for model, short in MODELS:
        for context in [100,500]:
            body.append([short,str(context),percent(model,'condition','context_truth',f'{context}:True','answer'),
                         percent(model,'condition','context_truth',f'{context}:False','answer'),
                         percent(model,'condition','context',context,'t01'),
                         percent(model,'condition','context',context,'target_bad_if_share')])
    table('tables/context_mechanisms.tex',
          r'Condition-aware context diagnostics (\%). Pos./neg. denote final-answer scores, T01 gives the attributed-error/exposure ratio, and A gives the target-directed share of attributed guard errors. Each polarity score has 5,832 questions per \texttt{class\_size} level.',
          'tab:context-mechanisms','lrrrrr',r'Model & \path{class_size} & Pos. & Neg. & T01 & A',body)

    body=[]
    for model, short in MODELS:
        for param in [1,2]:
            for key,name in [('if_difficulty_mean','D1'),('if_difficulty_attributable',r'D1$^*$'),
                             ('misjudged_if_difficulty_mean','D3'),('correct_if_difficulty_mean','D5'),
                             ('theoretical_if_difficulty_mean','D9')]:
                r=record(model,'condition','param',param,key)
                body.append([short,str(param),name,f"{float(r['value']):.3f}",f"{int(r['eligible']):,}",f"{int(r['denominator']):,}",f"{int(r['excluded']):,}"])
        body.append(None)
    table('tables/difficulty_populations.tex',
          r'Difficulty populations within condition-aware questions. Each \texttt{n\_params} level has 11,664 questions. The denominator counts resolved guard occurrences for D1/D1$^*$/D3/D5, and eligible questions for D9. Exclusions include zero resolved occurrences, missing origins, or ambiguous attribution as applicable.',
          'tab:difficulty-populations','llrrrrr',r'Model & \path{n_params} & Metric & Mean & Eligible questions & Denominator & Excluded',body[:-1],wide=True)

    body=[]
    for model,short in MODELS:
        for key in ['t01','t04','t05','t06','t07','t08','t09','t11','t13','target_bad_if_share',
                    'target_bad_if_case_incidence','false_positive_with_target_guard_error','false_positive_without_target_guard_error']:
            r=record(model,'condition','overall','all',key)
            name={'target_bad_if_share':'A','target_bad_if_case_incidence':'B',
                  'false_positive_with_target_guard_error':'FP with target-directed error',
                  'false_positive_without_target_guard_error':'FP without target-directed error'}.get(key,key.upper())
            n,d=r['numerator'],r['denominator']
            body.append([short,name,f"{100*float(r['value']):.2f}",f'{float(n):,.2f}' if n else '--',
                         f'{int(d):,}' if d else '--',f"{int(r['eligible']):,}",f"{int(r['excluded']):,}"])
        body.append(None)
    table('tables/diagnostic_populations.tex',
          r'Condition-aware diagnostic aggregates. Values are percentages, except for T09, which is a median with no sum denominator. Eligibility depends on the metric, so exclusions also include the other polarity for negative/positive-only diagnostics. For T04/T13, the numerator sums per-question fractions, not node counts. The two FP rows use unambiguously attributable negative records and condition on whether a target-directed guard error is present.',
          'tab:diagnostic-populations','llrrrrr',r'Model & Metric & Value & Numerator & Denominator & Eligible & Excluded',body[:-1],wide=True)

    body=[]
    for model,short in MODELS:
        for guards in [1,3,5]:
            body.append([short,str(guards),*[percent(model,'all','if',guards,k) for k in ['answer','path','t01','target_bad_if_share','target_bad_if_case_incidence','t05']]])
    table('tables/guard_mechanisms.tex',
          r'Guard diagnostics by \mbox{\texttt{n\_if}} (\%). A gives the target-directed share of attributed errors, while B gives the incidence of at least one such error in an eligible response. T05 applies only to the 5,832 negative questions per condition level. T01 uses the exposed-guard denominator, while A/B exclude ambiguous attributions.',
          'tab:guard-mechanisms','llrrrrrr',r'Model & \path{n_if} & Answer & Trace & T01 & A & B & T05',body,wide=True)

    body=[]
    for model,short in MODELS:
        for group,label in [('unguarded','Unguarded'),('condition','Condition-aware')]:
            body.append([short,label,f"{value(model,group,'overall','all','reasoning_token_count_mean'):,.0f}",
                         percent(model,group,'overall','all','reasoning_budget_usage_mean'),
                         f"{value(model,group,'overall','all','answer_token_count_mean'):,.0f}"])
    table('tables/token_observability.tex', r"Mean persisted reasoning and answer tokens, counted with each model's tokenizer. Usage gives reasoning tokens relative to the requested 16,384-token budget. These measurements describe output length rather than wall-clock compute or a budget intervention.",
          'tab:token-observability','llrrr',r'Model & Group & Reasoning tokens & Usage (\%) & Answer tokens',body,wide=True)

    def score_series(group, factor, levels, metrics):
        return [(short, metric, [(level, 100*value(model, group, factor, level, metric))
                                 for level in levels])
                for model, short in MODELS for metric in metrics]

    def plot(path, titles, label, series, axis_options, caption, description):
        legend = label.replace(':', '-') + '-legend'
        lines = [
            '% Generated by python3 scripts/render_results.py; source: data/results/aggregates.csv.',
            r'\begin{figure*}[t]', r'\centering', r'\begin{tikzpicture}',
            r'\begin{groupplot}[rb score axis, group style={group size=2 by 1, horizontal sep=1.3cm}]',
        ]
        for index, (title, curves, options) in enumerate(zip(titles, series, axis_options)):
            legend_options = f',legend to name={legend},legend columns={len(curves)}' if index == 0 else ',ylabel={}'
            lines.append(rf'\nextgroupplot[title={{({chr(97+index)}) {title}}},{options}{legend_options}]')
            for model, metric, points in curves:
                style = 'rb gemma' if model == 'Gemma' else 'rb qwen'
                # Signed distance has two populations, with no zero query.
                # Keep a visible break rather than joining opposite polarities.
                segments = [[p for p in points if p[0] < 0], [p for p in points if p[0] > 0]] if points[0][0] < 0 else [points]
                for segment_index, segment in enumerate(segments):
                    extra = ',forget plot' if segment_index else ''
                    coords = ' '.join(f'({x},{y:.4f})' for x,y in segment)
                    lines.append(rf'\addplot[{style},rb {metric}{extra}] coordinates {{{coords}}};')
                    if index == 0 and segment_index == 0:
                        metric_label = 'trace' if metric == 'path' else metric
                        lines.append(rf'\addlegendentry{{{model}}}' if len(curves) == 2 else rf'\addlegendentry{{{model}: {metric_label}}}')
            if curves[0][2][0][0] < 0:
                lines.append(r'\addplot[rbRule,densely dotted,no marks,forget plot] coordinates {(0,0) (0,100)};')
        lines += [r'\end{groupplot}',
                  r'\node[anchor=north,inner sep=0pt] at ($(group c1r1.south)!0.5!(group c2r1.south)+(0,-1.05cm)$) {\pgfplotslegendfromname{' + legend + '}};',
                  r'\end{tikzpicture}', rf'\caption{{{caption}}}',
                  rf'\Description{{{description}}}', rf'\label{{{label}}}', r'\end{figure*}', '']
        files[path] = '\n'.join(lines)

    guards = [0,1,3,5]
    parameters = [0,1,2]
    plot('figures/results_guards_parameters.tex', [r'\texttt{n\_if}',r'\texttt{n\_params}'],
         'fig:results-guards-parameters',
         [score_series('all','if',guards,['answer','path']),
          score_series('condition','param',parameters,['answer','path'])],
         [r'xmin=-0.2,xmax=5.2,xtick={0,1,3,5},xlabel={Generated guards ($\mathtt{n\_if}$)}',
          r'xmin=-0.1,xmax=2.1,xtick={0,1,2},xlabel={Parameters per method ($\mathtt{n\_params}$)}'],
         r'Scores by \mbox{\texttt{n\_if}} over all questions (a), and by \texttt{n\_params} within condition-aware questions (b). Other factors are balanced. The zero-value level of \mbox{\texttt{n\_if}} is the unguarded group.',
         'Two panels with correctness on the same zero-to-one-hundred percent scale. Circles denote Gemma and squares Qwen; solid lines denote answer correctness and dashed lines trace correctness.')

    distances = [-25,-22,-19,-16,-13,-10,-7,-4,-1,1,4,7,10,13,16,19,22,25]
    distance_axis = r'xmin=-27,xmax=27,xtick={-25,-13,0,13,25},xlabel={Signed generation distance}'
    plot('figures/results_distance.tex', ['Final-answer correctness','Trace correctness'],
         'fig:results-distance',
         [score_series('condition','distance',distances,['answer']),
          score_series('condition','distance',distances,['path'])],
         [distance_axis, distance_axis],
         r'Condition-aware scores by signed generation distance. Negative distances denote unreachable targets, while positive distances denote reachable targets. Each point has 1,944 questions per model. The dotted divider at zero separates the two populations, with no zero-distance query plotted.',
         'Answer and trace correctness by signed distance. The two polarity-specific curves stop on either side of zero. Model identity uses the same colors and markers as the other result figures.')

    contexts = [100,250,500]
    def context_series(truth):
        return [(short, metric, [(level,100*value(model,'condition','context_truth',f'{level}:{truth}',metric))
                                  for level in contexts])
                for model,short in MODELS for metric in ['answer','path']]
    context_axis = r'xmin=80,xmax=520,xtick={100,250,500},xlabel={\texttt{class\_size}}'
    plot('figures/results_context.tex', ['Reachable targets','Unreachable targets'],
         'fig:results-context', [context_series('True'),context_series('False')],
         [context_axis,context_axis],
         r'Condition-aware scores by class size, separated by polarity. Each point has 5,832 questions per model. Negative answer correctness rises while negative trace correctness falls.',
         'Correctness by class size in two polarity-specific panels. Solid answer lines and dashed trace lines use circles for Gemma and squares for Qwen, with a shared legend and percentage scale.')
    return files


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Fail if tracked tables/plots differ from the data.')
    args=parser.parse_args()
    files=render(ROOT)
    drift=[]
    for name,content in files.items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=content:drift.append(name)
        else:path.write_text(content)
    if drift:raise SystemExit('Generated drift: '+', '.join(drift))
    print(f'{"Checked" if args.check else "Rendered"} {len(files)} tables/figures.')


if __name__=='__main__':main()
