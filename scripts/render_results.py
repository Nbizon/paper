#!/usr/bin/env python3
"""Render manuscript tables and TikZ plots from data/results/aggregates.csv."""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = [('gemma-4-26B-A4B-it', 'Gemma'), ('qwen3.6-35B-A3B', 'Qwen')]


def render(root):
    with (root / 'data/results/aggregates.csv').open() as handle:
        rows = list(csv.DictReader(handle))
    index = {(r['model'], r['group'], r['factor'], r['level'], r['metric']): r for r in rows}
    files = {}

    def record(model, group, factor, level, metric):
        return index[model, group, factor, str(level), metric]

    def value(model, group, factor, level, metric):
        raw = record(model, group, factor, level, metric)['value']
        return float(raw) if raw else None

    def percent(model, group, factor, level, metric):
        v = value(model, group, factor, level, metric)
        return f'{100*v:.2f}' if v is not None else '--'

    def table(path, caption, label, columns, headings, body, wide=False, note=''):
        env = 'table*' if wide else 'table'
        files[path] = '\n'.join([
            '% Generated by python3 scripts/render_results.py; source: data/results/aggregates.csv.',
            rf'\begin{{{env}}}[t]', r'\centering', rf'\caption{{{caption}}}',
            rf'\label{{{label}}}', r'\scriptsize', r'\setlength{\tabcolsep}{3pt}',
            rf'\begin{{tabular}}{{{columns}}}', r'\toprule', headings + r' \\',
            r'\midrule', *[r'\midrule' if row is None else ' & '.join(row) + r' \\' for row in body],
            r'\bottomrule', r'\end{tabular}', note, rf'\end{{{env}}}', '',
        ])

    body = []
    for group, name in [('all', 'All'), ('unguarded', 'Unguarded'), ('condition', 'Condition-aware')]:
        for model, short in MODELS:
            n = record(model, group, 'overall', 'all', 'answer')['denominator']
            body.append([name, short, f'{int(n):,}', *[percent(model, group, 'overall', 'all', k) for k in ['answer','path','nr']]])
        body.append(None)
    table('tables/overall_performance.tex',
          r'Primary scores (\%). U: \texttt{nb\_if}$=0$; C: \texttt{nb\_if}$\in\{1,3,5\}$. Non-responses (NR) remain in both score denominators.',
          'tab:overall', 'llrrrr', r'Group & Model & $N$ & Answer & Path & NR', body[:-1])

    body = []
    for factor, label, low, high in [('if', 'Guards: 1 to 5', 1, 5), ('param','Parameters: 0 to 2',0,2),
                                    ('context','Methods: 100 to 500',100,500), ('comment','Comments: 0 to 1',0,1),
                                    ('var','Variables: 0 to 2',0,2), ('loop','Loops: 0 to 2',0,2)]:
        fields = [label]
        for model, short in MODELS:
            for metric in ['answer','path']:
                group = 'all' if factor == 'if' else 'condition'
                delta = 100*(value(model,group,factor,high,metric)-value(model,group,factor,low,metric))
                fields.append(f'{delta:+.2f}')
        body.append(fields)
    table('tables/factor_effects.tex', r'Marginal contrasts within condition-aware questions (percentage points, high minus low). Other factors are averaged over the balanced grid.',
          'tab:factors','lrrrr',r'Contrast & Gemma A & Gemma P & Qwen A & Qwen P',body)

    body=[]
    for model, short in MODELS:
        for truth, label in [('True','Positive'),('False','Negative')]:
            body.append([short,label,*[percent(model,'condition','expected_truth',truth,k) for k in ['answer','path','t04','t05']]])
    table('tables/trace_diagnostics.tex', r'Condition-aware scores by polarity (\%). Each polarity has 17,496 questions per model. T04 is the mean omitted fraction; T05 is the incidence of an existing method outside the executable region. Both are negative-only diagnostics.',
          'tab:trace-diagnostics','llrrrr',r'Model & Polarity & Answer & Path & T04 & T05',body)

    body=[]
    for model, short in MODELS:
        for param in [1,2]:
            fields=[short,str(param)]
            for key in ['if_difficulty_attributable','misjudged_if_difficulty_mean','correct_if_difficulty_mean','theoretical_if_difficulty_mean']:
                fields.append(f'{value(model,"condition","param",param,key):.2f}')
            body.append(fields)
    table('tables/value_origin_difficulty.tex',
          r'Value-origin distance in method boundaries. D1$^*$ restricts D1 to the same unambiguous attribution population as D3/D5. D3 denotes attributed errors; D5 denotes exposed guards without an attributed error. D9 is question-weighted reference difficulty. Counts appear in Table~\ref{tab:difficulty-populations}.',
          'tab:value-origin','lrrrrr',r'Model & Param. & D1$^*$ & D3 & D5 & D9',body)

    body=[]
    for model, short in MODELS:
        for context in [100,500]:
            body.append([short,str(context),percent(model,'condition','context_truth',f'{context}:True','answer'),
                         percent(model,'condition','context_truth',f'{context}:False','answer'),
                         percent(model,'condition','context',context,'t01'),
                         percent(model,'condition','context',context,'target_bad_if_share')])
    table('tables/context_mechanisms.tex',
          r'Condition-aware context diagnostics (\%). Pos./neg. are final-answer scores; T01 is the attributed-error/exposure ratio; A is the target-directed share of attributed guard errors. Each polarity score has 5,832 questions per class-size level.',
          'tab:context-mechanisms','lrrrrr',r'Model & Methods & Pos. & Neg. & T01 & A',body)

    body=[]
    for model, short in MODELS:
        for param in [1,2]:
            for key,name in [('if_difficulty_mean','D1'),('if_difficulty_attributable',r'D1$^*$'),
                             ('misjudged_if_difficulty_mean','D3'),('correct_if_difficulty_mean','D5'),
                             ('theoretical_if_difficulty_mean','D9')]:
                r=record(model,'condition','param',param,key)
                body.append([short,str(param),name,f"{float(r['value']):.3f}",f"{int(r['eligible']):,}",f"{int(r['denominator']):,}",f"{int(r['excluded']):,}"])
        body.append(None)
    table('tables/difficulty_populations.tex',
          r'Difficulty populations within condition-aware questions. Each parameter level has 11,664 questions. The denominator counts resolved guard occurrences for D1/D1$^*$/D3/D5, and eligible questions for D9. Exclusions include zero resolved occurrences, missing origins, or ambiguous attribution as applicable.',
          'tab:difficulty-populations','llrrrrr',r'Model & Param. & Metric & Mean & Eligible questions & Denominator & Excluded',body[:-1],wide=True)

    body=[]
    for model,short in MODELS:
        for key in ['t01','t04','t05','t06','t07','t08','t09','t11','t13','target_bad_if_share',
                    'target_bad_if_case_incidence','false_positive_with_target_guard_error','false_positive_without_target_guard_error']:
            r=record(model,'condition','overall','all',key)
            name={'target_bad_if_share':'A','target_bad_if_case_incidence':'B',
                  'false_positive_with_target_guard_error':'FP with target-directed error',
                  'false_positive_without_target_guard_error':'FP without target-directed error'}.get(key,key.upper())
            n,d=r['numerator'],r['denominator']
            body.append([short,name,f"{100*float(r['value']):.2f}",f'{float(n):,.2f}' if n else '--',
                         f'{int(d):,}' if d else '--',f"{int(r['eligible']):,}",f"{int(r['excluded']):,}"])
        body.append(None)
    table('tables/diagnostic_populations.tex',
          r'Condition-aware diagnostic aggregates. Values are percentages; T09 is a median with no sum denominator. Eligibility depends on the metric, so exclusions also include the other polarity for negative/positive-only diagnostics. For T04/T13, the numerator sums per-question fractions, not node counts. The two FP rows use unambiguously attributable negative records and condition on whether a target-directed guard error is present.',
          'tab:diagnostic-populations','llrrrrr',r'Model & Metric & Value & Numerator & Denominator & Eligible & Excluded',body[:-1],wide=True)

    body=[]
    for model,short in MODELS:
        for guards in [1,3,5]:
            body.append([short,str(guards),*[percent(model,'all','if',guards,k) for k in ['answer','path','t01','target_bad_if_share','target_bad_if_case_incidence','t05']]])
    table('tables/guard_mechanisms.tex',
          r'Guard diagnostics (\%). A is the target-directed share of attributed errors; B is the incidence of at least one such error in an eligible response. T05 applies only to the 5,832 negative questions per guard level. T01 uses the exposed-guard denominator; A/B exclude ambiguous attributions.',
          'tab:guard-mechanisms','llrrrrrr',r'Model & Guards & Answer & Path & T01 & A & B & T05',body,wide=True)

    body=[]
    for model,short in MODELS:
        for group,label in [('unguarded','Unguarded'),('condition','Condition-aware')]:
            body.append([short,label,f"{value(model,group,'overall','all','reasoning_token_count_mean'):,.0f}",
                         percent(model,group,'overall','all','reasoning_budget_usage_mean'),
                         f"{value(model,group,'overall','all','answer_token_count_mean'):,.0f}"])
    table('tables/token_observability.tex', r'Mean persisted reasoning and answer tokens, counted with each model\'s tokenizer. Usage is reasoning tokens divided by the requested 16,384-token budget. These are output measurements, not wall-clock compute or a budget intervention.',
          'tab:token-observability','llrrr',r'Model & Group & Reasoning tokens & Usage (\%) & Answer tokens',body,wide=True)

    def panel(title, levels, series, ticklabels=None):
        width=6.8
        low,high=min(levels),max(levels)
        positions=[width*(level-low)/(high-low) if high!=low else width/2 for level in levels]
        lines=[r'\begin{tikzpicture}[x=1cm,y=0.035cm]',rf'\node[font=\small] at (3.4,113) {{{title}}};']
        for tick in [0,25,50,75,100]:
            lines += [rf'\draw[gray!20] (0,{tick}) -- (6.8,{tick});',rf'\node[anchor=east,font=\scriptsize] at (-0.08,{tick}) {{{tick}}};']
        lines += [r'\draw[gray!60] (0,100) -- (0,0) -- (6.8,0);']
        for i,level in enumerate(levels):
            label=ticklabels[i] if ticklabels else str(level)
            lines.append(rf'\node[anchor=north,font=\scriptsize] at ({positions[i]:.3f},-2) {{{label}}};')
        if low<0<high:
            zero=width*(0-low)/(high-low)
            lines.append(rf'\draw[gray!50,dotted] ({zero:.3f},0) -- ({zero:.3f},100);')
        for label,color,dashed,vals in series:
            coords=' '.join(f'({positions[i]:.3f},{v:.4f})' for i,v in enumerate(vals))
            style=f'{color},line width=0.9pt'+(',dashed' if dashed else '')
            lines.append(rf'\draw[{style}] plot coordinates {{{coords}}};')
            for i,v in enumerate(vals):
                lines.append(rf'\fill[{color}] ({positions[i]:.3f},{v:.4f}) circle (1.2pt);')
        lines.append(r'\end{tikzpicture}')
        return '\n'.join(lines)

    def plot(path,title,label,levels,left,right,caption,ticklabels=None,right_levels=None):
        files[path]='\n'.join([
            '% Generated by python3 scripts/render_results.py; source: data/results/aggregates.csv.',
            r'\begin{figure*}[t]',r'\centering',panel(title[0],levels,left,ticklabels=ticklabels),r'\hfill',panel(title[1],right_levels if right_levels is not None else levels,right,ticklabels=ticklabels),
            r'\par\smallskip\scriptsize Qwen: blue; Gemma: orange. Solid: answer; dashed: path.',
            rf'\caption{{{caption}}}',rf'\label{{{label}}}',r'\end{figure*}', '',
        ])

    def score_series(group,factor,levels,metrics):
        return [(f'{short} {metric}', 'modelorange' if short=='Gemma' else 'modelblue',metric=='path',
                 [100*value(model,group,factor,level,metric) for level in levels])
                for model,short in MODELS for metric in metrics]

    levels=[0,1,3,5]
    plot('figures/results_guards_parameters.tex',['Number of guards','Number of parameters'],
         'fig:results-guards-parameters',levels,score_series('all','if',levels,['answer','path']),
         score_series('condition','param',[0,1,2],['answer','path']),
         r'Scores (\%) by guard count over all questions (left), and by parameter count within condition-aware questions (right). All other factors are balanced. The zero-guard level is the unguarded group.',right_levels=[0,1,2])

    levels=[-25,-22,-19,-16,-13,-10,-7,-4,-1,1,4,7,10,13,16,19,22,25]
    labels=[str(x) if i%2==0 or x==25 else '' for i,x in enumerate(levels)]
    plot('figures/results_distance.tex',['Final-answer correctness','Path correctness'],'fig:results-distance',levels,
         score_series('condition','distance',levels,['answer']),score_series('condition','distance',levels,['path']),
         r'Condition-aware scores (\%) by signed generation distance. Negative distances denote unreachable targets. Each point has 1,944 questions per model. The dotted line separates polarities; there is no zero-distance query.',ticklabels=labels)

    levels=[100,250,500]
    def context_series(truth):
        return [(f'{short} {metric}','modelorange' if short=='Gemma' else 'modelblue',metric=='path',
                 [100*value(model,'condition','context_truth',f'{level}:{truth}',metric) for level in levels])
                for model,short in MODELS for metric in ['answer','path']]
    plot('figures/results_context.tex',['Reachable targets','Unreachable targets'],'fig:results-context',levels,
         context_series('True'),context_series('False'),
         r'Condition-aware scores (\%) by class size, separated by polarity. Each point has 5,832 questions per model. Negative answer correctness rises while negative path correctness falls.')
    return files


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Fail if tracked tables/plots differ from the data.')
    args=parser.parse_args()
    files=render(ROOT)
    drift=[]
    for name,content in files.items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=content:drift.append(name)
        else:path.write_text(content)
    if drift:raise SystemExit('Generated drift: '+', '.join(drift))
    print(f'{"Checked" if args.check else "Rendered"} {len(files)} tables/figures.')


if __name__=='__main__':main()
