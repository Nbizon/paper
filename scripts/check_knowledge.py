#!/usr/bin/env python3
"""Validate the current JSON-subset YAML knowledge records and generated index.

Historical specifications.md is retained as a supersession archive. Current
records use JSON objects between YAML front-matter delimiters (valid YAML), so
this focused checker needs no third-party YAML parser.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-index', action='store_true')
    args = parser.parse_args()
    records = {}
    bodies = {}
    for directory, prefix in [('docs/product-specs', 'SPEC'), ('docs/changes', 'CHG')]:
        for path in sorted((ROOT / directory).glob('*.md')):
            front, body = path.read_text().split('---\n', 2)[1:]
            record = json.loads(front)
            identifier = record['id']
            assert re.fullmatch(prefix + r'-[A-Za-z0-9-]+', identifier), identifier
            assert path.name.startswith(identifier + '-'), path
            assert identifier not in records, identifier
            assert record['schema_version'] == '1.0'
            records[identifier] = (record, path)
            bodies[identifier] = body
    for identifier, (record, path) in records.items():
        if identifier.startswith('SPEC-'):
            assert record['record_type'] in {'requirement','constraint','assumption','observation','question'}
            assert record['intent_status'] in {'proposed','active','rejected','superseded','withdrawn'}
            assert record['delivery_status'] in {'not_started','in_progress','partially_implemented','implemented','not_applicable'}
            assert record['verification_status'] in {'unverified','verified','failed','stale','not_applicable'}
            assert record['source']['actor'] in {'user','repository','external','agent'}
            assert record['source']['mode'] in {'explicit','derived','assumed','observed'}
            assert record['introduced_by'] in records
            change = records[record['introduced_by']][0]
            assert identifier in change['related_specs']
            for relation in ['depends_on','conflicts_with','derived_from','supersedes','superseded_by','related_to']:
                for target in record['relations'][relation]:
                    assert target in records, target
            assert not record['traceability']['adrs'], 'No ADR is introduced by this change'
            for group in ['code','tests','docs']:
                for name in record['traceability'][group]:
                    target = Path(name)
                    assert not target.is_absolute() and '..' not in target.parts, name
                    assert (ROOT / target).is_file(), name
            if record['intent_status'] == 'active' and record['record_type'] in {'requirement','constraint'}:
                assert re.search(r'- AC-\d+:', bodies[identifier])
            commits = record['traceability']['commits']
            if record['delivery_status'] == 'implemented' or record['verification_status'] == 'verified':
                assert commits, identifier
            if record['verification_status'] == 'verified':
                evidence = record['verification_evidence']
                assert evidence['method'] != 'unknown' and evidence['confidence'] != 'unknown'
                assert evidence['verified_at'] and evidence['evidence'] and record['traceability']['tests']
                for name in evidence['evidence']:
                    assert (ROOT / name).is_file(), name
            assert set(commits) <= set(change['commits'])
        else:
            assert record['status'] in {'planned','in_progress','verifying','completed','abandoned'}
            assert record['risk'] in {'L1','L2','L3'}
            for spec in record['related_specs']:
                assert spec in records
                if record['status'] == 'completed':
                    assert records[spec][0]['delivery_status'] == 'implemented'
                    assert records[spec][0]['verification_status'] == 'verified'
            assert not record['related_adrs'], 'No ADR is introduced by this change'
            commits = record['commits']
            if record['status'] == 'completed':
                assert commits and record['related_specs']
        for commit in commits:
            assert re.fullmatch('[0-9a-f]{40}', commit), commit
            subprocess.run(['git','cat-file','-e',commit+'^{commit}'],cwd=ROOT,check=True)
    lines = ['<!-- Generated by python3 scripts/check_knowledge.py --write-index; sources: docs/product-specs/SPEC-*.md and docs/changes/CHG-*.md. -->',
             '# Current specifications', '', '| Specification | Intent | Delivery | Verification | Change |', '|---|---|---|---|---|']
    for identifier,(record,path) in sorted(records.items()):
        if not identifier.startswith('SPEC-'): continue
        change=records[record['introduced_by']][1]
        lines.append(f"| [{identifier}](../product-specs/{path.name}) | {record['intent_status']} | {record['delivery_status']} | {record['verification_status']} | [{record['introduced_by']}](../changes/{change.name}) |")
    content='\n'.join(lines)+'\n'
    index=ROOT/'docs/generated/spec-index.md'
    if args.write_index:
        index.parent.mkdir(parents=True,exist_ok=True)
        index.write_text(content)
    else:
        assert index.read_text()==content, 'Generated specification index is stale'
    print(f'Validated {len(records)} current records and specification index.')


if __name__=='__main__': main()
