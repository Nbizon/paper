#!/usr/bin/env python3
"""Reproduce Figure 1 from the inspected construction algorithm, without inference."""

import argparse
import json
from pathlib import Path
import random
import re
import sys


ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generator-root', required=True, type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    # The external generator directory is a read-only input, including caches.
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(args.generator_root.resolve()))
    from experiment_config import TreeCallExperimentConfig
    from tree_chain_generator import generate_execution_tree, generate_tree_method_calls
    from java_entrypoint import render_main_launcher

    directory = ROOT / 'examples/design'
    metadata = json.loads((directory / 'selection.json').read_text())
    random.seed(metadata['seed'])
    config = TreeCallExperimentConfig(name='figure-1', seed=metadata['seed'],
                                      n_questions=1, **metadata['config'])
    trees, _ = generate_execution_tree(config)
    bodies = generate_tree_method_calls(trees, config)
    random.shuffle(bodies)
    java = 'public class TheClass {\n' + '\n'.join(bodies) + '\n}\n'
    java = '\n'.join(line.rstrip() for line in java.splitlines()) + '\n'
    launcher = render_main_launcher(trees[0].name)
    graph = {n.name: n.execution_trace for n in trees[0].get_all_nodes()}
    assert len(graph) == config.context_size == 4
    assert trees[0].name == metadata['root']
    assert graph[metadata['source']] == [metadata['positive_target']]
    source_node = next(n for n in trees[0].get_all_nodes() if n.name == metadata['source'])
    assert source_node.params[0].value == metadata['value'] == 4
    assert graph[metadata['positive_target']] == []
    assert metadata['negative_target'] not in graph[metadata['source']]

    compact = re.sub(r'if \(([^\n]*)\) \{\n\s*(System\.out\.println\([^\n]*\);)\n\s*\}',
                     r'if (\1) { \2 }', java)
    compact = '\n'.join(line.replace('\t', '  ').rstrip()
                        for line in compact.splitlines() if line.strip()) + '\n'
    assert re.sub(r'\s+', '', compact) == re.sub(r'\s+', '', java)
    figure = (
        '% Generated by python3 scripts/render_design_example.py; '
        'sources: examples/design/selection.json and the inspected code_generation.\n'
        '% Only whitespace is compacted; no method, call, declaration or guard is removed.\n'
        '\\begin{figure}[t]\n\\centering\n\\begin{minipage}{\\columnwidth}\n'
        '\\footnotesize\n\\texttt{TheClass.java}\n\\begin{verbatim}\n' + compact +
        '\\end{verbatim}\n\\texttt{Main.java}\n\\begin{verbatim}\n' +
        launcher.replace('    ', '  ') + '\\end{verbatim}\n\\end{minipage}\n'
        '\\caption{Complete four-method illustration produced by the construction algorithm. '
        'Only whitespace is compacted. The root supplies the value 4; '
        '\\texttt{sortJobForRequest} executes from the root but is not reachable from '
        '\\texttt{buildSessionToBuffer}, whose visible call to it is disabled.}\n'
        '\\label{fig:background-example}\n\\end{figure}\n'
    )
    outputs = {directory / 'TheClass.java': java, directory / 'Main.java': launcher,
               directory / 'executable_graph.json': json.dumps(graph, indent=2),
               ROOT / 'figures/generated_java_example.tex': figure}
    for path, content in outputs.items():
        if args.check:
            assert path.read_text() == content, f'Generated drift: {path}'
        else:
            path.write_text(content)
    print('Four-method example and figure ' + ('match.' if args.check else 'written.'))


if __name__ == '__main__':
    main()
