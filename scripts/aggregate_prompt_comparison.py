#!/usr/bin/env python3
"""Extract prompt comparisons from archived HTML data without executing scripts."""

import argparse
import base64
from collections import Counter
import gzip
import hashlib
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
PROMPT_LABELS = {'v1': 'CO', 'v4': 'EE'}
FACTORS = ('case', 'context', 'comment', 'var', 'loop', 'if', 'param',
           'distance', 'expected_truth')


def load_dashboard(path):
    html = path.read_text()
    payload = json.loads(re.search(
        r'<script id="embedded-results" type="application/json">(.*?)</script>',
        html, re.S)[1])
    assert payload['encoding'] == 'gzip-base64-columnar-json'
    models = {}
    for model in payload['models']:
        data = json.loads(gzip.decompress(base64.b64decode(model['data'])))
        columns, dictionaries = data['columns'], data['dictionaries']
        models[model['name']] = [
            {key: dictionaries[key][values[i]]
             if key in dictionaries and values[i] is not None else values[i]
             for key, values in columns.items()}
            for i in range(data['rows'])]
    return models


def summarize(rows):
    assert rows and all(row['inference_status'] == 'OK' for row in rows)
    result = {'questions': len(rows), 'classes': len({r['case'] for r in rows}),
              'budgets': sorted({r['reasoning_budget'] for r in rows})}
    for name, field, outcome in (
        ('answer', 'correctness_answer', 'TRUE'),
        ('path', 'correctness_path', 'TRUE'),
        ('no_response', 'correctness_answer', 'NO_RESPONSE'),
    ):
        assert all(r[field] in {'TRUE', 'FALSE', 'NO_RESPONSE'} for r in rows)
        count = sum(r[field] == outcome for r in rows)
        result[name] = {'numerator': count, 'denominator': len(rows),
                        'percent': 100 * count / len(rows)}
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results-root', required=True, type=Path,
                        help='Parent containing last_exp, last_exp_7 and last_exp_6')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = {
        'Qwen3.6': 'last_exp_7/dashboard/comparaison_qwen36_35b_last_exp_vs_last_exp_7.html',
        'Gemma': 'last_exp_7/dashboard/comparaison_gemma4_last_exp_vs_last_exp_7.html',
        'Qwen3.8': 'last_exp_6/dashboards/nouvelles_metriques_qwen38_4.html',
    }
    report = {'sources': {}, 'comparisons': {},
              'interpretation': 'Gemma common support is provisional; Qwen3.6/Gemma budgets differ.'}
    table = [
        '% Generated by python3 scripts/aggregate_prompt_comparison.py; source: data/prompt_comparison/summary.json.',
        r'\begin{table}[t]', r'\centering',
        r'\caption{Prompt comparisons on common questions (\%). CO: Class-only; EE: Explicit execution. Reasoning budgets (CO/EE): 16,384/32,768 for Gemma and Qwen3.6; 16,384/16,384 for Qwen3.8. Gemma$^\dagger$ uses provisional common support.}',
        r'\label{tab:prompt-comparison}', r'\scriptsize',
        r'\setlength{\tabcolsep}{3pt}', r'\begin{tabular}{llrrrr}',
        r'\toprule', r'Model & Prompt & $N$ & Answer & Path & NR \\', r'\midrule',
    ]
    for label, relative in files.items():
        path = args.results_root / relative
        report['sources'][relative] = hashlib.sha256(path.read_bytes()).hexdigest()
        models = load_dashboard(path)
        if label == 'Qwen3.8':
            pair = [models[f'Qwen3.8-Flash-Next (prompt {v})'] for v in ('v1', 'v4')]
        else:
            assert len(models) == 2
            pair = [next(rows for name, rows in models.items() if f' {exp} ' in name)
                    for exp in ('last_exp', 'last_exp_7')]
        assert Counter(tuple(r[k] for k in FACTORS) for r in pair[0]) == Counter(
            tuple(r[k] for k in FACTORS) for r in pair[1]), label
        if label == 'Gemma':
            assert 0 < len(pair[0]) <= 46656
        else:
            assert len(pair[0]) == {'Qwen3.6': 46656, 'Qwen3.8': 216}[label]
        report['comparisons'][label] = {}
        for version, rows in zip(('v1', 'v4'), pair):
            summary = {'all': summarize(rows)}
            for family, subset in (
                ('unguarded', [r for r in rows if r['if'] == 0]),
                ('condition', [r for r in rows if r['if'] > 0]),
                ('positive', [r for r in rows if r['expected_truth'] == 'True']),
                ('negative', [r for r in rows if r['expected_truth'] == 'False']),
            ):
                if subset:
                    summary[family] = summarize(subset)
            report['comparisons'][label][version] = summary
            stats = summary['all']
            model = r'Gemma$^\dagger$' if label == 'Gemma' else label
            table.append(f"{model} & {PROMPT_LABELS[version]} & {len(rows):,} & "
                         f"{stats['answer']['percent']:.2f} & {stats['path']['percent']:.2f} & "
                         f"{stats['no_response']['percent']:.2f}" + r' \\')
        table.append(r'\midrule' if label != 'Qwen3.8' else r'\bottomrule')
    table.extend([r'\end{tabular}', r'\end{table}', ''])
    outputs = {
        ROOT / 'data/prompt_comparison/summary.json': json.dumps(report, indent=2) + '\n',
        ROOT / 'tables/prompt_comparison.tex': '\n'.join(table),
    }
    for path, content in outputs.items():
        if args.check:
            assert path.read_text() == content, f'Generated drift: {path}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('Validated three common-support comparisons; summary and table ' +
          ('match.' if args.check else 'written.'))


if __name__ == '__main__':
    main()
